/* 별하 일본어 — 학습 내용
 *
 * 레슨을 늘릴 때는 이 파일만 고치면 된다.
 *   kana(글자, 한글발음, 도움말)
 *   word(일본어, 한글발음, 뜻)
 *   num(숫자표기, 가나, 한글발음)
 *   ph(id, 일본어, 가나, 한글발음, 뜻, [[조각, 조각발음], ...], 검수여부)
 *
 * ph 의 마지막 값(검수여부)은 일본어 가능자가 확인한 문장만 true 로 바꾼다.
 */
'use strict';

const ITEMS = {};

function kana(ch, pron, tip) {
  const id = 'k_' + ch;
  ITEMS[id] = { id, g: 'kana', jp: ch, say: ch, kana: ch, pron, ko: pron, tip: tip || '' };
  return id;
}
function word(jp, pron, ko) {
  const id = 'w_' + jp;
  ITEMS[id] = { id, g: 'word', jp, say: jp, kana: jp, pron, ko };
  return id;
}
function num(jp, kn, pron) {
  const id = 'n_' + jp;
  ITEMS[id] = { id, g: 'num', jp, say: kn, kana: kn, pron, ko: jp };
  return id;
}
function ph(id, jp, kn, pron, ko, parts, ok) {
  ITEMS[id] = { id, g: 'phrase', jp, say: jp, kana: kn, pron, ko, parts: parts || null, ok: !!ok };
  return id;
}

